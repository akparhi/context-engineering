export type ReviewLines = {
  plan: string; title: string; revision: string; by: string; result: keyof typeof COPY.submit.result
  approved: string[]; sentBack: { title: string; note: string }[]; answered: { id: string; title: string; answer: string }[]
  comments: { on: string; text: string }[]; open: string[]; unanswered: { id: string; title: string }[]; defaults: string[]
}

/** The text a reviewer sends back. People read the lines. `ingest` reads only the fenced payload. */
export function reviewText(r: ReviewLines, payload: string) {
  const list = (head: string, rows: string[], inline = false) =>
    rows.length ? (inline ? `${head} (${rows.length}): ${rows.join(", ")}` : `${head} (${rows.length}):\n${rows.map((row) => `  ${row}`).join("\n")}`) : ""
  const RESULT_WORD = { approved: "approved", partial: "partial", changes: "changes requested" } as const
  return [
    `sign-off review of ${r.plan} ${r.title}, plan ${r.revision}`,
    `Reviewer: ${r.by}`,
    `Result: ${RESULT_WORD[r.result]}`,
    "",
    ...[
      list("Approved", r.approved, true),
      list("Sent back", r.sentBack.map((s) => `${s.title}: ${s.note}`)),
      list("Answered", r.answered.map((a) => `${a.id} ${a.title} ${a.answer}`)),
      list("Comments", r.comments.map((c) => `${c.on}: ${c.text}`)),
      list("Not decided", r.open, true),
      list("Not answered", r.unanswered.map((q) => `${q.id} ${q.title}`), true),
      r.defaults.length ? `Defaults that stand: ${r.defaults.join(", ")}` : "",
    ].filter(Boolean),
    "",
    "Send this whole message back as it is. The fenced line is what the agent reads.",
    "",
    "```",
    payload,
    "```",
  ].join("\n")
}
