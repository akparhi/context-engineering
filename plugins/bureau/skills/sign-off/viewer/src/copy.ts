export function holdLine(hold: number, rest: number) {
  const word = (n: number) => COUNT_WORD[n] ?? String(n)
  return [
    hold ? `${word(hold)} ${hold === 1 ? "holds" : "hold"} the plan.` : "",
    rest ? `${word(rest)} ${rest === 1 ? "runs" : "run"} on a default.` : "",
  ].filter(Boolean).join(" ")
}

